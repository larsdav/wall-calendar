// Inlines public/ (plus src/tz.js and src/logic.js, served as /lib/*) into src/assets.gen.js,
// then bundles one self-contained Worker to dist/worker.js.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const root = new URL('..', import.meta.url).pathname;
const pub = join(root, 'public');
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.webmanifest': 'application/manifest+json', '.txt': 'text/plain; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png' };
const files = []; // [servedName, fullPath]
(function walk(dir) { for (const f of readdirSync(dir).sort()) { const full = join(dir, f); if (statSync(full).isDirectory()) walk(full); else if (TYPES[extname(f)]) files.push([relative(pub, full).split('\\').join('/'), full]); } })(pub);
files.push(['lib/tz.js', join(root, 'src/tz.js')], ['lib/logic.js', join(root, 'src/logic.js')]);
const all = createHash('sha256');
for (const [n, f] of files) all.update(n).update(readFileSync(f));
const version = all.digest('hex').slice(0, 12);
const assets = {};
for (const [name, full] of files) {
  let buf = readFileSync(full);
  if (name === 'sw.js') buf = Buffer.from(buf.toString('utf8').replace('__VERSION__', version));
  const h = createHash('sha256').update(buf).digest('hex').slice(0, 10);
  assets[name] = extname(full) === '.png' ? { type: TYPES['.png'], b64: buf.toString('base64'), h } : { type: TYPES[extname(full)], body: buf.toString('utf8'), h };
}
writeFileSync(join(root, 'src/assets.gen.js'), `// GENERATED by scripts/build.mjs — do not edit\nexport const ASSET_VERSION = ${JSON.stringify(version)};\nexport const ASSETS = ${JSON.stringify(assets)};\n`);
mkdirSync(join(root, 'dist'), { recursive: true });
execFileSync(join(root, 'node_modules/.bin/esbuild'), ['src/worker.js', '--bundle', '--format=esm', '--outfile=dist/worker.js', '--log-level=warning'], { cwd: root, stdio: 'inherit' });
console.log(`version ${version}: ${files.length} assets, dist/worker.js ${statSync(join(root, 'dist/worker.js')).size} bytes`);
